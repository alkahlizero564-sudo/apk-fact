import { getFileText, pushFile } from "./github";
import { REPO } from "./config";
import { runSql, getSupabaseClientInfo } from "./supabase";
import { askText, generateApp } from "./generate2";

type Status = (s: string) => void;

function cleanName(n: string) {
  return n.trim().toLowerCase().replace(/[^a-z0-9-]/g, "");
}

function limit(s: string, n: number) {
  return s.length > n ? s.slice(0, n) : s;
}

const DESIGN_SYSTEM = [
  "You design ONE shared Supabase (Postgres) schema for two small web apps that belong to the same project.",
  "Reply in EXACTLY this format and nothing else:",
  "===SUMMARY===",
  "(one short line in Arabic)",
  "===SQL===",
  "(SQL statements separated by semicolons)",
  "===SCHEMA===",
  "(plain English: each table, its columns with types, and which app reads or writes what)",
  "",
  "SQL rules:",
  "- Only these statement types: CREATE TABLE IF NOT EXISTS, ALTER TABLE ... ENABLE ROW LEVEL SECURITY, DROP POLICY IF EXISTS, CREATE POLICY, GRANT, CREATE INDEX IF NOT EXISTS.",
  "- Every table is in schema public and its name MUST start with the given prefix.",
  "- Primary keys: uuid primary key default gen_random_uuid(), or bigint generated by default as identity. Never serial.",
  "- Add created_at timestamptz default now() to every table.",
  "- For every table: enable row level security; DROP POLICY IF EXISTS then CREATE POLICY one policy per operation (select, insert, update, delete) for roles anon, authenticated. Select and delete use USING (true). Insert uses WITH CHECK (true). Update uses USING (true) WITH CHECK (true).",
  "- Also GRANT select, insert, update, delete on each table to anon, authenticated, and GRANT usage on schema public to anon, authenticated.",
  "- No functions, triggers, DO blocks, extensions, comments, or semicolons inside strings.",
  "- Keep it minimal: only the tables the two apps really need to persist or share.",
].join("\n");

function section(text: string, name: string): string {
  const re = new RegExp("===" + name + "===([\\s\\S]*?)(?====[A-Z]+===|$)");
  const m = text.match(re);
  return m ? m[1].trim() : "";
}

function validateSql(raw: string, prefix: string): string[] {
  const text = raw
    .replace(/```[a-z]*/gi, "")
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/--.*$/gm, "");
  const statements = text
    .split(";")
    .map((s) => s.replace(/\s+/g, " ").trim())
    .filter(Boolean);

  if (!statements.length) throw new Error("ما في أوامر SQL في رد التصميم.");
  if (statements.length > 80) throw new Error("عدد أوامر SQL أكتر من اللازم.");

  const allowedStart = [
    /^create table if not exists public\./i,
    /^alter table public\.[a-z0-9_]+ enable row level security$/i,
    /^drop policy if exists /i,
    /^create policy /i,
    /^grant /i,
    /^create (unique )?index if not exists /i,
  ];
  const forbidden =
    /\b(drop\s+(table|schema|database|role|user|function|trigger|extension|view|column)|truncate|delete\s+from|alter\s+(role|user|database|system|schema)|create\s+(role|user|function|trigger|extension|schema|view)|insert\s+into|copy\s|pg_[a-z_]+|auth\.|storage\.|supabase_|vault\.|extensions\.)/i;

  for (const st of statements) {
    if (!allowedStart.some((re) => re.test(st))) {
      throw new Error("أمر SQL غير مسموح: " + st.slice(0, 80));
    }
    if (forbidden.test(st)) {
      throw new Error("أمر SQL فيه شي ممنوع: " + st.slice(0, 80));
    }
    if (/^grant /i.test(st)) {
      if (/\ball\s+(tables|sequences|functions)\b/i.test(st)) {
        throw new Error("GRANT على كل الجداول ممنوع: " + st.slice(0, 80));
      }
      if (!/\bto (anon|authenticated)(, ?(anon|authenticated))*$/i.test(st)) {
        throw new Error("GRANT لجهة غير مسموحة: " + st.slice(0, 80));
      }
    }
    const refs = st.match(/public\.([a-z0-9_]+)/gi) || [];
    for (const r of refs) {
      const t = r.slice(7).toLowerCase();
      if (!t.startsWith(prefix)) {
        throw new Error("اسم جدول لازم يبدأ بـ " + prefix + " : " + t);
      }
    }
  }
  return statements;
}

function rewriteDesc(
  me: string,
  other: string,
  otherHtml: string,
  schema: string,
  url: string,
  key: string
): string {
  return [
    'This app ("' + me + '") and another app ("' + other + '") are two parts of ONE project.',
    "They now share a Supabase database that is already created and ready.",
    "Rewrite THIS app so that all its data is saved to and loaded from Supabase instead of local-only storage, so both apps see the same data.",
    "Rules:",
    "- Keep the same design, language and features. Only change how data is saved and loaded.",
    '- Put these two constants at the top of the script: const SUPABASE_URL = "' + url + '"; const SUPABASE_ANON_KEY = "' + key + '";',
    "- Use plain fetch against SUPABASE_URL + '/rest/v1/<table>' with headers apikey and Authorization: Bearer <anon key>, Content-Type application/json, and Prefer: return=representation for inserts and updates. Do NOT load any external library.",
    "- Use ONLY these tables and columns:",
    schema,
    "- Refresh data from Supabase every 5 seconds so changes made in the other app show up here.",
    "- Show a small Arabic error message in the UI if a request fails.",
    "",
    "For consistency, here is the other app's code (do not copy it):",
    "<other_app_code>",
    limit(otherHtml, 40000),
    "</other_app_code>",
  ].join("\n");
}

export async function linkAppsViaSupabase(
  nameA: string,
  nameB: string,
  onStatus: Status
): Promise<{ summary: string; tables: string[] }> {
  const a = cleanName(nameA);
  const b = cleanName(nameB);
  if (!a || !b) throw new Error("اكتب اسمي التطبيقين (الأول والتاني).");
  if (a === b) throw new Error("اسم التطبيقين لازم يكون مختلف.");

  onStatus("⏳ بقرا التطبيقين من GitHub...");
  const htmlA = await getFileText(REPO, "apps/" + a + "/index.html");
  const htmlB = await getFileText(REPO, "apps/" + b + "/index.html");
  if (!htmlA) throw new Error("التطبيق (" + a + ") مش موجود. اعمل إنشاء الأول.");
  if (!htmlB) throw new Error("التطبيق (" + b + ") مش موجود. اعمل إنشاء الأول.");

  onStatus("⏳ بجيب رابط ومفتاح Supabase...");
  const info = await getSupabaseClientInfo();

  const prefix = "p_" + a.replace(/-/g, "_") + "_";
  const designPrompt = [
    "Table name prefix (every table MUST start with it): " + prefix,
    "",
    '<app name="' + a + '">',
    limit(htmlA, 60000),
    "</app>",
    "",
    '<app name="' + b + '">',
    limit(htmlB, 60000),
    "</app>",
  ].join("\n");

  onStatus("⏳ الذكاء الاصطناعي بيصمم الجداول والصلاحيات...");
  const design = await askText(DESIGN_SYSTEM, designPrompt, onStatus);
  const summary = section(design.text, "SUMMARY");
  const sqlRaw = section(design.text, "SQL");
  const schema = section(design.text, "SCHEMA");
  if (!sqlRaw || !schema) throw new Error("رد التصميم ناقص. جرّب تاني.");

  const statements = validateSql(sqlRaw, prefix);
  const tables = statements
    .map((s) => s.match(/^create table if not exists public\.([a-z0-9_]+)/i))
    .filter((m): m is RegExpMatchArray => !!m)
    .map((m) => m[1]);

  onStatus("⏳ بنفذ " + statements.length + " أمر SQL على Supabase...");
  for (const st of statements) {
    try {
      await runSql(st);
    } catch (e: any) {
      throw new Error("فشل أمر SQL: " + st.slice(0, 80) + "...\n" + (e?.message || e));
    }
  }
  onStatus("✅ الجداول والصلاحيات جاهزة: " + tables.join("، "));

  onStatus("⏳ بعيد كتابة " + a + "...");
  const ra = await generateApp(
    rewriteDesc(a, b, htmlB, schema, info.url, info.anonKey),
    htmlA,
    onStatus
  );
  onStatus("⏳ بعيد كتابة " + b + "...");
  const rb = await generateApp(
    rewriteDesc(b, a, htmlA, schema, info.url, info.anonKey),
    htmlB,
    onStatus
  );

  onStatus("⏳ برفع التطبيقين على GitHub...");
  await pushFile(REPO, "apps/" + a + "/index.html", ra.html + "\n", "Link via Supabase: " + a);
  await pushFile(REPO, "apps/" + b + "/index.html", rb.html + "\n", "Link via Supabase: " + b);

  return { summary, tables };
    }
